    private void guardarArchivo() {
        try (BufferedWriter escritor = Files.newBufferedWriter(archivo, StandardCharsets.UTF_8)) {
            for (Producto p : Productos.values()) {
                escritor.write(p.getNombre() + "|" + p.getMarca() + "|" + p.getTamaño() + "|" + p.getPeso() + "|" + p.getStock());
                escritor.newLine();
            }
        } catch (IOException error) {
            JOptionPane.showMessageDialog(this, "Error al guardar: " + error.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
        }
    }

    private void cargarArchivo() {
        if (!Files.exists(archivo)) {
            return;
        }
        try (BufferedReader lector = Files.newBufferedReader(archivo, StandardCharsets.UTF_8)) {
            String linea;
            while ((linea = lector.readLine()) != null) {
                String[] datos = linea.split("\\|", -1);
                // Leemos 5 datos (el último es el stock)
                if (datos.length >= 5) {
                    Producto producto = new Producto(datos[0], datos[1], datos[2], datos[3], Integer.parseInt(datos[4]));
                    Productos.put(datos[0], producto);
                }
            }
        } catch (Exception error) {
            JOptionPane.showMessageDialog(this, "Error al cargar el archivo.", "Error", JOptionPane.ERROR_MESSAGE);
        }
    }

   private void mostrarProductos() {
        VerRegistros.setText("");
        VerRegistros.append(String.format("%-15s %-15s %-15s %-10s %-10s%n", "Nombre", "Marca", "Tamaño", "Peso", "Stock"));
        VerRegistros.append("------------------------------------------------------------------------\n");
        
        for (Producto producto : Productos.values()) {
            // Imprime los datos generales del artículo
            VerRegistros.append(String.format("%-15s %-15s %-15s %-10s %-10s%n", 
                producto.getNombre(), producto.getMarca(), producto.getTamaño(), producto.getPeso(), producto.getStock()));
            
            // Si el producto tiene movimientos, los imprime debajo
            if (!producto.getHistorial().isEmpty()) {
                VerRegistros.append("   [Historial de Movimientos]:\n");
                for (Movimiento mov : producto.getHistorial()) {
                    
                    VerRegistros.append(String.format("      -> Artículo: %s | %s | Cant: %d | Fecha: %s | Resp: %s%n", 
                        producto.getNombre(), mov.getTipo(), mov.getCantidad(), mov.getFecha(), mov.getResponsable()));
                }
                VerRegistros.append("\n"); // Salto de línea para separar del siguiente producto
            }
        }
    }

