    private void btnRegistrarArticuloActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnRegistrarArticuloActionPerformed
        String nombre = txtNombre.getText().trim();
        String brand = txtMarca.getText().trim();
        String tamaño = txtTamaño.getText().trim();
        String peso = txtPeso.getText().trim();

        if (nombre.isEmpty() || brand.isEmpty() || tamaño.isEmpty() || peso.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Debes llenar todos los campos del artículo.");
            return;
        }

        if (nombre.contains("|") || brand.contains("|") || tamaño.contains("|") || peso.contains("|")) {
            JOptionPane.showMessageDialog(this, "No se permite el uso del carácter |.");
            return;
        }

        if (Productos.containsKey(nombre)) {
            JOptionPane.showMessageDialog(this, "Ya existe un artículo con ese nombre.");
            return;
        }

        // Se crea el artículo con 0 en stock
        Producto nuevoProducto = new Producto(nombre, brand, tamaño, peso, 0);
        Productos.put(nombre, nuevoProducto);

        guardarArchivo();
        mostrarProductos();
        limpiarCamposArticulo();

        JOptionPane.showMessageDialog(this, "Artículo creado. Registra un movimiento para añadirle stock.");        // TODO add your handling code here:
    }//GEN-LAST:event_btnRegistrarArticuloActionPerformed

    private void btnRegistrarMovimientoActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnRegistrarMovimientoActionPerformed
        String articulo = txtArticulo.getText().trim();
        String cantidadStr = txtCantidad.getText().trim();
        String tipo = txtTipo.getText().trim();
        String id = txtID.getText().trim();
        String fecha = txtFecha.getText().trim();
        String responsable = txtResponsable.getText().trim();

        if (articulo.isEmpty() || cantidadStr.isEmpty() || tipo.isEmpty() || id.isEmpty() || fecha.isEmpty() || responsable.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Todos los campos de movimiento son obligatorios.");
            return;
        }

        if (!tipo.equalsIgnoreCase("Entrada") && !tipo.equalsIgnoreCase("Salida")) {
            JOptionPane.showMessageDialog(this, "El tipo debe ser exactamente 'Entrada' o 'Salida'.");
            return;
        }

        if (!Productos.containsKey(articulo)) {
            JOptionPane.showMessageDialog(this, "El artículo no existe. Regístralo primero en 'NUEVO ARTICULO'.");
            return;
        }

        try {
            int cantidad = Integer.parseInt(cantidadStr);
            if (cantidad <= 0) {
                JOptionPane.showMessageDialog(this, "La cantidad debe ser mayor a 0.");
                return;
            }

            Producto prod = Productos.get(articulo);

            if (tipo.equalsIgnoreCase("Salida") && prod.getStock() < cantidad) {
                JOptionPane.showMessageDialog(this, "No hay suficiente stock. Tienes: " + prod.getStock());
                return;
            }

            // Registrar e impactar stock
            Movimiento mov = new Movimiento(id, tipo, cantidad, fecha, responsable);
            prod.registrarMovimiento(mov);

            guardarArchivo();
            mostrarProductos();

            // Limpiar campos del movimiento
            txtArticulo.setText("");
            txtCantidad.setText("");
            txtTipo.setText("");
            txtID.setText("");
            txtFecha.setText("");
            txtResponsable.setText("");

            JOptionPane.showMessageDialog(this, "Movimiento exitoso. Nuevo stock de " + articulo + ": " + prod.getStock());

        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "La cantidad debe ser un número entero.");
        }        // TODO add your handling code here:
    }//GEN-LAST:event_btnRegistrarMovimientoActionPerformed

