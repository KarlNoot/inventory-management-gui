        public void registrarMovimiento(Movimiento mov) {
            if (mov.getTipo().equalsIgnoreCase("Entrada")) {
                this.stock += mov.getCantidad();
            } else if (mov.getTipo().equalsIgnoreCase("Salida")) {
                this.stock -= mov.getCantidad();
            }
            this.historialMovimientos.add(mov);
        }

